"""Cuts join points for GuildRadioFM Live: for every song, copies that start 30, 60, 90... seconds in.
A listener who tunes in mid-song waits for the next join point and starts that copy, landing in time.
Writes GuildRadioFM/Songs/_join/<song>/<sec>.mp3 and GuildRadioFM/JoinPoints.lua.
Run after adding songs:  python tools/make_joins.py   (needs ffmpeg + lupa)"""
import os
import re
import shutil
import subprocess
import lupa

STEP = 30
BITRATE = "128k"
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..", "GuildRadioFM") if os.path.isdir(os.path.join(HERE, "..", "GuildRadioFM")) else os.path.join(HERE, "..")
SONG_FILES = ["SongList.lua", "NoyzeKomplaynt.lua"]


def songs():
    L = lupa.LuaRuntime()
    L.execute("GuildRadioFM = { RegisterSongPack = function(p) for _, s in ipairs(p.songs) do table.insert(_PACK, s) end end }; _PACK = {}")
    for f in SONG_FILES:
        L.execute(open(os.path.join(ROOT, f), encoding="utf-8").read())
    out = []
    for tbl in (L.globals().GuildRadioFMSongList, L.globals()._PACK):
        for i in range(1, len(tbl) + 1):
            s = tbl[i]
            out.append((s.title, s.file))
    return out


def key_of(title):  # must match EB.KeyOf in Live.lua
    return re.sub(r"[~:,|]", "", title.lower())


def slug(key):
    return re.sub(r"[^a-z0-9]+", "-", key).strip("-")


def duration(path):
    r = subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", path],
                       capture_output=True, text=True)
    return float(r.stdout.strip())


def main():
    join_root = os.path.join(ROOT, "Songs", "_join")
    shutil.rmtree(join_root, ignore_errors=True)
    lines = ["-- Generated by tools/make_joins.py. Join points for GuildRadioFM Live (copies of each song starting N seconds in).",
             "GuildRadioFMJoins = {"]
    total = 0
    for title, wow_path in songs():
        rel = wow_path.replace("Interface\\AddOns\\GuildRadioFM\\", "").replace("\\", os.sep)
        src = os.path.join(ROOT, rel)
        if not os.path.exists(src):
            print("missing", src)
            continue
        dur = duration(src)
        k = key_of(title)
        sl = slug(k)
        out_dir = os.path.join(join_root, sl)
        os.makedirs(out_dir, exist_ok=True)
        points = []
        p = STEP
        while p < dur - 10:
            dst = os.path.join(out_dir, f"{p}.mp3")
            # -ss after -i = sample-accurate cut
            subprocess.run(["ffmpeg", "-v", "error", "-y", "-i", src, "-ss", str(p), "-map", "0:a", "-c:a", "libmp3lame",
                            "-b:a", BITRATE, "-map_metadata", "-1", dst], check=True)
            total += os.path.getsize(dst)
            points.append(p)
            p += STEP
        lua_dir = "Interface\\\\AddOns\\\\GuildRadioFM\\\\Songs\\\\_join\\\\" + sl + "\\\\"
        lines.append(f'    ["{k}"] = {{ dir = "{lua_dir}", points = {{ {", ".join(map(str, points))} }} }},')
        print(f"{title}: {len(points)} join points ({dur:.0f}s)")
    lines.append("}")
    open(os.path.join(ROOT, "JoinPoints.lua"), "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
    print(f"total join audio: {total / 1e6:.1f} MB")


if __name__ == "__main__":
    main()
